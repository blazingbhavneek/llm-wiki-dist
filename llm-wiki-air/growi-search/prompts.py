"""Prompts for the finder (JEV questions), researchers, lead check and compiler."""

# -- JEV yes/no questions (the finder; no LLM) --------------------------------

def jev_direct_question(question: str) -> str:
    """A: does this section answer the question directly?"""
    return ("上記の節は、次の質問に対する答えそのもの（求められた値・定義・一覧・手順・説明）を、"
            "この節の中で直接述べていますか？\n"
            f"質問: {question}\n"
            "関連する話題に触れているだけ、名前が出てくるだけ、他の節やページへの案内だけの場合は "
            "いいえ と答えてください。\n選択肢: はい / いいえ")


def jev_helps_question(question: str) -> str:
    """B: does this section help answer it?"""
    return ("上記の節は、次の質問に答えるために読むべき手がかり（関係する仕組み・条件・定義・"
            "動作・一覧の一部・原因や結果など）を含んでいますか？\n"
            f"質問: {question}\n"
            "同じ製品や分野というだけで、質問の対象に具体的に関係しない場合は いいえ と答えてください。\n"
            "選択肢: はい / いいえ")


